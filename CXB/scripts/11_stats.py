"""Statistics for the paper, exactly as fixed in docs/decisions.md before the final runs.

Unit of analysis = fake-label split (mean over seeds and folds), because the 10 folds of a
split share training subjects. For each comparison: mean difference, 95% bootstrap CI over
splits, and a two-sided sign test. Accuracy is pooled over all test subjects. Writes
docs/stats.md.

    .venv\\Scripts\\python.exe scripts\\11_stats.py
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import binomtest, ttest_1samp

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "final"
SMALL_SITE_FOLDS = (0, 1)        # SBL and CALTECH: under 10 fake-label test subjects
NAMES = {"plain": "Plain", "combat": "ComBat, no EB", "combat_protect": "ComBat, no EB (label protected)",
         "combat_eb": "ComBat (standard, EB)", "combat_protect_eb": "ComBat (standard, EB, label protected)",
         "siteswap_aug": "CF-Site", "siteswap_eb": "CF-Site (EB swap)", "siteswap": "CF-Site + penalty",
         "siteswap_oracle": "Oracle CF-Site (perfect swap)"}
out = ["# Statistics (final runs)", "",
       "Generated by `scripts/11_stats.py` from `results/final/` (not in git). Plan fixed in `docs/decisions.md` "
       "before the runs. Unit = fake-label split (mean over seeds and folds); CI = 95% bootstrap over splits; "
       "p = two-sided sign test and paired t-test over splits. Accuracy pooled over all test subjects.", ""]


def boot_ci(d, n=10000, seed=0):
    rng = np.random.default_rng(seed)
    means = rng.choice(d, (n, len(d)), replace=True).mean(1)
    return np.percentile(means, [2.5, 97.5])


def sign_p(d):
    d = d[d != 0]
    return binomtest(int((d > 0).sum()), len(d)).pvalue if len(d) else 1.0


def pooled_acc(g):
    return float((g.test_acc * g.n_test).sum() / g.n_test.sum())


def t_p(d):
    """Two-sided paired t-test over splits (added 1 Nov, next to the sign test)."""
    return float(ttest_1samp(d, 0).pvalue) if len(d) > 1 and np.std(d) > 0 else 1.0


def compare(df, a, b, col):
    s = df.groupby(["split", "method"])[col].mean().unstack()
    d = (s[a] - s[b]).to_numpy()
    lo, hi = boot_ci(d)
    return d.mean(), lo, hi, int((d > 0).sum()), len(d), sign_p(d), t_p(d)


MODEL_ORDER = ["mlp", "gcn", "gat", "brainnetcnn", "braingnn", "bnt"]
MODEL_NAMES = {"mlp": "MLP", "gcn": "GCN", "gat": "GAT", "brainnetcnn": "BrainNetCNN", "braingnn": "BrainGNN", "bnt": "BNT"}


def holm(ps):
    """Holm step-down adjusted p-values (same order as given)."""
    ps = np.asarray(ps, float)
    order = np.argsort(ps)
    adj, run = np.empty_like(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def primary_family(df, title):
    """Rule of decisions.md (1 Nov, F1): CF-Site minus best standard ComBat and minus plain,
    disease AUPRC, per model; gain only if the CI excludes 0 and the Holm-adjusted t-test p < 0.05."""
    rows = []
    for model in [m for m in MODEL_ORDER if m in set(df.model)]:
        g = df[df.model == model]
        std = [m for m in ("combat_eb", "combat_protect_eb") if m in set(g.method)]
        if "siteswap_aug" not in set(g.method) or not std:
            continue
        cb = g[g.method.isin(std)].groupby("method").disease_auprc.mean().idxmax()
        for b in (cb, "plain"):
            if b in set(g.method):
                rows.append((model, b, *compare(g, "siteswap_aug", b, "disease_auprc")))
    if not rows:
        return
    adj = holm([r[-1] for r in rows])
    out.extend([f"## {title}", "",
                "Rule fixed before the runs: a gain needs the 95% CI to exclude 0 and the Holm-adjusted t-test p < 0.05 "
                f"(family of {len(rows)} tests); otherwise tie (or loss).", "",
                "| Model | Comparison | Disease AUPRC difference | 95% CI | Splits better | Sign test p | t-test p | Holm p | Verdict |",
                "|---|---|---|---|---|---|---|---|---|"])
    for (model, b, m_, lo, hi, k, n, p, tp), a in zip(rows, adj):
        v = "gain" if lo > 0 and a < 0.05 else ("loss" if hi < 0 and a < 0.05 else "tie")
        out.append(f"| {MODEL_NAMES[model]} | CF-Site − {NAMES[b]} | {m_:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {k}/{n} | "
                   f"{p:.3f} | {tp:.3f} | {a:.3f} | {v} |")
    out.append("")


def drift_table(d, title, models):
    out.extend([f"## {title}", "",
                "| Model | Metric | At 50% | At 90% | Difference | 95% CI | Splits | t-test p |", "|---|---|---|---|---|---|---|---|"])
    for model in models:
        for col in ["scanner_share", "disease_auprc", "test_acc"]:
            s_ = d[d.model == model].groupby(["split", "frac"])[col].mean().unstack()
            if 0.9 not in s_ or 0.5 not in s_:
                continue
            dd = (s_[0.9] - s_[0.5]).to_numpy()
            lo, hi = boot_ci(dd)
            out.append(f"| {MODEL_NAMES[model]} | {col} | {s_[0.5].mean():.2f} | {s_[0.9].mean():.2f} | {dd.mean():+.3f} | "
                       f"[{lo:+.3f}, {hi:+.3f}] | {(dd > 0).sum()}/{len(dd)} | {t_p(dd):.3f} |")
    out.append("")


def pretty_model(m):
    """'bnt-half-lr0.001' -> 'BNT (tuned: half width, lr 0.001)'."""
    base, *opts = str(m).split("-")
    name = MODEL_NAMES.get(base, base)
    if not opts:
        return name
    parts = ["half width" if o == "half" else f"lr {o[2:]}" for o in opts]
    return f"{name} (tuned: {', '.join(parts)})"


def base_model(m):
    return str(m).split("-")[0]


def methods_section(df, title, main_cmp=True):
    out.extend([f"## {title}", ""])
    present = [m for m in MODEL_ORDER if m in set(df.model)]
    for model in present:
        g = df[df.model == model]
        methods = [m for m in NAMES if m in g.method.unique()]
        out.extend([f"### {MODEL_NAMES[model]}", "",
                    "| Method | Disease AUPRC | Median | Runs > 0.5 | Scanner share | Accuracy (pooled) |", "|---|---|---|---|---|---|"])
        for m in methods:
            h = g[g.method == m]
            runs = h.groupby(["split", "seed"]).disease_auprc.mean()
            acc = np.mean([pooled_acc(x) for _, x in h.groupby(["split", "seed"])])
            out.append(f"| {NAMES[m]} | {h.disease_auprc.mean():.2f} | {h.disease_auprc.median():.2f} | "
                       f"{(h.disease_auprc > 0.5).mean():.0%} | {h.scanner_share.mean():.2f} | {acc:.3f} |")
        cb = g[g.method.str.startswith("combat")].groupby("method").disease_auprc.mean().idxmax()
        out.extend(["", f"Best ComBat variant: {NAMES[cb]}.", "",
                    "| Comparison | Metric | Difference | 95% CI | Splits better | Sign test p | t-test p |", "|---|---|---|---|---|---|---|"])
        pairs = [("siteswap_aug", cb), ("siteswap_aug", "plain")]
        if "siteswap_eb" in methods:
            pairs.append(("siteswap_eb", cb))
        for a, b in pairs:
            for col, lab in [("disease_auprc", "Disease AUPRC"), ("scanner_share", "Scanner share"), ("test_acc", "Accuracy")]:
                m_, lo, hi, k, n, p, tp = compare(g, a, b, col)
                out.append(f"| {NAMES[a]} − {NAMES[b]} | {lab} | {m_:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {k}/{n} | {p:.3f} | {tp:.3f} |")
        if main_cmp:
            h = g[~g.fold.isin(SMALL_SITE_FOLDS)]
            m_, lo, hi, k, n, p, tp = compare(h, "siteswap_aug", cb, "disease_auprc")
            out.append(f"| Without SBL, CALTECH: CF-Site − {NAMES[cb]} | Disease AUPRC | {m_:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {k}/{n} | {p:.3f} | {tp:.3f} |")
        out.append("")


