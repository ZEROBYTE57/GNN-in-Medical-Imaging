def controls_and_models():
    f = RES / "controls" / "controls.csv"
    if f.exists():
        c = pd.read_csv(f)
        out.extend(["## 7. Controls (x2 planted effect; splits 0-2)", "",
                    "Chance AUPRC is 0.008. Shuffled labels: training and validation labels permuted, so nothing real can be learned. "
                    "Logistic regression: L2, C chosen on validation loss; explanation = |coefficient|.", "",
                    "| Control | Model | Explainer | Disease AUPRC | Scanner share | Accuracy (pooled) |", "|---|---|---|---|---|---|"])
        for (ctl, model, ex), h in c.groupby(["control", "model", "explainer"]):
            acc = np.mean([pooled_acc(x) for _, x in h.groupby(["split", "seed"])])
            sc = f"{h.scanner_share.mean():.2f}" if h.scanner_share.notna().any() else "–"
            out.append(f"| {ctl} | {MODEL_NAMES.get(model, model)} | {ex} | {h.disease_auprc.mean():.3f} | {sc} | {acc:.3f} |")
        out.append("")
    gates = sorted((RES / "models").glob("gate1_*/gate1_*.csv"))
    if gates:
        g = pd.concat([pd.read_csv(x) for x in gates], ignore_index=True)
        g = g[g.explainer == "saliency"] if "explainer" in g else g
        out.extend(["## 8. Additional models: sanity test (x4, no shortcut, splits 0-2, seed 0; pass if saliency group AUPRC >= 0.5)", "",
                    "| Model | Group AUPRC (saliency) | Accuracy (pooled) | Pass |", "|---|---|---|---|"])
        for model, h in g.groupby("model"):
            acc = pooled_acc(h)
            out.append(f"| {pretty_model(model)} | {h.group_auprc.mean():.2f} | {acc:.3f} | {'yes' if h.group_auprc.mean() >= 0.5 else 'no'} |")
        for t in sorted((RES / "models").glob("tune_*.json")):
            import json
            j = json.loads(t.read_text())
            out.append("")
            out.append(f"Tuning ({t.stem[5:]}, validation loss only): " + ", ".join(f"{k} {v:.3f}" for k, v in j["losses"].items())
                       + f"; chosen {j['chosen']}.")
        out.append("")
    parts = sorted((RES / "models").glob("*/methods/gate3_*.csv"))
    if parts:
        m = pd.concat([pd.read_csv(x) for x in parts], ignore_index=True)
        m = m[(m.design == "train") & (m.explainer == "saliency")].copy()
        m["model"] = m.model.map(base_model)
        seeds = ", ".join(str(int(x)) for x in sorted(m.seed.unique())) if "seed" in m else "0"
        methods_section(m, f"9. Additional models: methods comparison (main setting, splits 0-2, seeds {seeds})", main_cmp=False)
    parts = sorted((RES / "models").glob("*/drift/gate2_*.csv"))
    if parts:
        d = pd.concat([pd.read_csv(x) for x in parts], ignore_index=True)
        d = d[(d.explainer == "saliency") & (d.design == "train")].copy()
        d["model"] = d.model.map(base_model)
        drift_table(d, "10. Additional models: drift, 90% vs 50% shortcut (saliency)", [x for x in MODEL_ORDER if x in set(d.model)])


