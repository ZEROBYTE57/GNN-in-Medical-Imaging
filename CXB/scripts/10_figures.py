from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RES, FIG = ROOT / "results" / "final", ROOT / "docs" / "figures"   # final paper runs
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300"]
MARKERS = ["o", "s", "^", "D", "v", "P"]
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3de"
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                     "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "lines.linewidth": 2,
                     "legend.frameon": False, "figure.dpi": 200, "axes.axisbelow": True, "savefig.bbox": "tight"})
EXPL = {"saliency": "Saliency", "ig": "Integrated Gradients", "gnnexplainer": "GNNExplainer-style mask"}
METH = {"plain": "Plain", "combat": "ComBat, no EB", "combat_protect": "ComBat, no EB\n(label protected)",
        "combat_eb": "ComBat", "combat_protect_eb": "ComBat\n(label protected)",
        "siteswap_aug": "CF-Site", "siteswap_eb": "CF-Site\n(EB swap)", "siteswap": "CF-Site\n+ penalty",
        "siteswap_oracle": "Oracle\nCF-Site"}
TICK = {"plain": "Plain", "combat_eb": "ComBat", "combat_protect_eb": "ComBat\nprotected", "siteswap_aug": "CF-Site",
        "siteswap_eb": "CF-Site\nEB swap", "siteswap_oracle": "Oracle\nCF-Site"}
FIG3 = list(TICK)  # figure shows standard (EB) ComBat; tables keep every method
md = ["# Results summary", "", "Generated by `scripts/10_figures.py` from the CSV files in `results/` (not in git).",
      "Mean ± SD over runs (each run = one fake-label split × seed, averaged over the 10 site folds).", ""]


def per_run(df, keys, cols, run=("split", "seed")):
    """Average over folds within each run, then mean and SD over runs."""
    run = [r for r in run if r in df.columns]
    g = df.groupby(keys + run)[cols].mean().reset_index()
    return g.groupby(keys)[cols].agg(["mean", "std"])


def fmt(m, s):
    return f"{m:.2f} ± {s:.2f}" if np.isfinite(s) else f"{m:.2f}"


def clip_err(m, sd, lo=0.0, hi=1.0):
    """Asymmetric error bars (mean +- SD) cut at the metric's range, so no bar goes past 0 or 1."""
    m, sd = np.asarray(m, float), np.nan_to_num(np.asarray(sd, float))
    return np.vstack([m - np.maximum(m - sd, lo), np.minimum(m + sd, hi) - m])


def fig_recovery():
    f = RES / "benchmark" / "benchmark.csv"
    if not f.exists():
        return
    df = pd.read_csv(f)
    levels = ["x1", "x2", "x4"]
    s = per_run(df, ["model", "explainer", "level"], ["group_auprc", "subject_auprc", "test_acc", "ceiling_auprc"])
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9), sharey=True)
    for ax, model in zip(axes, ["mlp", "gcn"]):
        ceil = [s.loc[(model, "saliency", lv), ("ceiling_auprc", "mean")] for lv in levels]
        ax.plot(levels, ceil, color=MUTED, ls="--", lw=1.2, label="t-test reference (training subjects)")
        ax.axhline(0.008, color=MUTED, ls=":", lw=1, label="Chance")
        for i, ex in enumerate([e for e in EXPL if (model, e, "x1") in s.index]):
            m = [s.loc[(model, ex, lv), ("group_auprc", "mean")] for lv in levels]
            sd = [s.loc[(model, ex, lv), ("group_auprc", "std")] for lv in levels]
            ax.errorbar(levels, m, yerr=clip_err(m, sd), color=SERIES[i], marker=MARKERS[i], ms=6, capsize=3, label=EXPL[ex])
        ax.set_title(model.upper(), color=INK, loc="left", fontsize=10)
        ax.set_xlabel("Planted strength")
        ax.set_ylim(0, 1.05)
    axes[0].set_ylabel("Planted-edge recovery (AUPRC)")
    h, lab = axes[1].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=5, fontsize=7.5, bbox_to_anchor=(0.5, -0.16))
    fig.savefig(FIG / "fig1_recovery.png")
    plt.close(fig)
    md.extend(["## 1. Explainer recovery of the planted effect (benchmark table)", "",
               "| Model | Explainer | Strength | Test accuracy | Group AUPRC | Subject AUPRC | t-test reference |", "|---|---|---|---|---|---|---|"])
    for (model, ex, lv), r in s.iterrows():
        md.append(f"| {model.upper()} | {EXPL[ex]} | {lv} | {fmt(*r['test_acc'])} | {fmt(*r['group_auprc'])} | "
                  f"{fmt(*r['subject_auprc'])} | {r[('ceiling_auprc', 'mean')]:.2f} |")
    md.append("")


def fig_drift():
    files = sorted((RES / "drift").glob("gate2_*drift.csv"))
    if not files:
        return
    df = pd.read_csv(files[-1])
    df = df[(df.explainer == "saliency") & (df.design == "train")]
    s = per_run(df, ["model", "frac"], ["scanner_share", "scanner_share_wide", "disease_auprc", "test_acc"])
    fig, axes = plt.subplots(1, 3, figsize=(9.6, 2.8))
    panels = [("scanner_share", "Scanner share of top-45 edges"), ("disease_auprc", "Disease recovery (AUPRC)"),
              ("test_acc", "Test accuracy")]
    for ax, (col, title) in zip(axes, panels):
        for i, model in enumerate(["mlp", "gcn"]):
            fr = sorted(df.frac.unique())
            m = [s.loc[(model, f), (col, "mean")] for f in fr]
            sd = [s.loc[(model, f), (col, "std")] for f in fr]
            ax.errorbar([int(100 * f) for f in fr], m, yerr=clip_err(m, sd), color=SERIES[i], marker=MARKERS[i], ms=6, capsize=3,
                        label=model.upper())
        ax.set_title(title, color=INK, loc="left", fontsize=9.5)
        ax.set_xlabel("Patients with scanner B in training (%)")
        ax.set_ylim(0, 1.02)
    axes[0].legend(loc="upper left")
    fig.text(0.01, -0.1, "Mean over 3 splits x 3 seeds x 10 site folds; error bars: SD over the 9 runs, cut at 0 and 1.",
             fontsize=7, color=MUTED)
    fig.savefig(FIG / "fig2_drift.png")
    plt.close(fig)
    md.extend(["## 2. Scanner shortcut drift (train-only shortcut, saliency, disease x2)", "",
               "| Model | Shortcut | Test accuracy | Disease AUPRC | Scanner share (45 decoy edges) | Scanner share (wide; chance ~0.15) |",
               "|---|---|---|---|---|---|"])
    for (model, fr), r in s.iterrows():
        md.append(f"| {model.upper()} | {int(100 * fr)}% | {fmt(*r['test_acc'])} | {fmt(*r['disease_auprc'])} | "
                  f"{fmt(*r['scanner_share'])} | {fmt(*r['scanner_share_wide'])} |")
    md.append("")


def fig_methods():
    parts = [pd.read_csv(f) for f in sorted((RES / "methods").glob("gate3_*.csv")) if not f.stem.replace("_eb", "").endswith(("_edge", "_setB"))]
    if not parts:
        return
    df = pd.concat(parts, ignore_index=True)
    df = df[(df.explainer == "saliency")]
    if "seed" not in df.columns:
        df["seed"] = 0
    s = per_run(df, ["design", "model", "method"], ["disease_auprc", "scanner_share", "test_acc"])
    order = [m for m in FIG3 if m in df.method.unique()]
    fig, axes = plt.subplots(2, 2, figsize=(8.4, 5.2), sharex=True)
    for c, model in enumerate(["mlp", "gcn"]):
        for r, (col, title) in enumerate([("disease_auprc", "Disease recovery (AUPRC)"), ("scanner_share", "Scanner share")]):
            ax = axes[r, c]
            vals = [s.loc[("train", model, m), (col, "mean")] for m in order]
            errs = [s.loc[("train", model, m), (col, "std")] for m in order]
            yerr = clip_err(vals, errs)
            bars = ax.bar(range(len(order)), vals, yerr=yerr, width=0.7, color=SERIES[0],
                          edgecolor="white", linewidth=2, capsize=3, error_kw={"ecolor": MUTED, "lw": 1})
            for b, m in zip(bars, order):
                if m == "siteswap_oracle":
                    b.set_hatch("////")
                    b.set_facecolor("#9ec5f4")
            for b, v, e in zip(bars, vals, yerr[1]):
                ax.text(b.get_x() + b.get_width() / 2, v + e + 0.02, f"{v:.2f}", ha="center", fontsize=6.5, color=INK)
            ax.set_ylim(0, 1.12)
            ax.set_yticks(np.arange(0, 1.01, 0.2))
            ax.set_title(f"{model.upper()}: {title}", color=INK, loc="left", fontsize=9.5)
            ax.grid(axis="x", visible=False)
    for ax in axes[1]:
        ax.set_xticks(range(len(order)), [TICK[m] for m in order], fontsize=7)
    fig.text(0.01, -0.05, "Shortcut 90% in training, 50/50 in test; saliency; 6 splits x 3 seeds x 10 site folds. ComBat = standard (empirical Bayes). Error bars: SD over the 18 runs, cut at 0 and 1.\n"
             "Hatched: oracle CF-Site, using the true other-scanner scan (upper bound, not usable in practice). GCN spread is wide because GCN runs tend to find the effect fully or not at all.",
             fontsize=7, color=MUTED)
    fig.savefig(FIG / "fig3_methods.png")
    plt.close(fig)
    md.extend(["## 3. Fixing the shortcut: ComBat vs CF-Site (90% shortcut, saliency, 6 splits x 3 seeds)", "",
               "| Design | Model | Method | Test accuracy | Disease AUPRC | Scanner share |", "|---|---|---|---|---|---|"])
    for (design, model, m), r in s.iterrows():
        md.append(f"| {design} | {model.upper()} | {METH[m].replace(chr(10), ' ')} | {fmt(*r['test_acc'])} | "
                  f"{fmt(*r['disease_auprc'])} | {fmt(*r['scanner_share'])} |")
    md.append("")


def fig_real():
    files = [f for f in (RES / "real_labels" / "real_labels.csv", RES / "real_labels_eb" / "real_labels.csv") if f.exists()]
    if not files:
        return
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    df = df[df.explainer == "saliency"]
    s = per_run(df, ["model", "method"], ["test_acc", "test_auc", "site_spearman", "site_top_share"], run=("seed",))
    order = [m for m in ["plain", "combat_protect_eb", "siteswap_aug"] if m in df.method.unique()]
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8))
    for ax, (col, title) in zip(axes, [("test_auc", "Real autism labels: test AUC"),
                                       ("site_spearman", "Explanation vs site effect (Spearman)")]):
        w = 0.36
        for i, model in enumerate(["mlp", "gcn"]):
            vals = [s.loc[(model, m), (col, "mean")] for m in order]
            errs = [s.loc[(model, m), (col, "std")] for m in order]
            ax.bar(np.arange(len(order)) + (i - 0.5) * w, vals, w, yerr=errs, color=SERIES[i], edgecolor="white",
                   linewidth=2, capsize=3, error_kw={"ecolor": MUTED, "lw": 1}, label=model.upper(),
                   hatch=None if i == 0 else "\\\\\\")
        ax.set_xticks(range(len(order)), [METH[m] for m in order], fontsize=7.5)
        ax.set_title(title, color=INK, loc="left", fontsize=9.5)
        ax.grid(axis="x", visible=False)
        if col == "test_auc":
            ax.axhline(0.5, color=MUTED, ls=":", lw=1)
            ax.set_ylim(0.3, 0.8)
        else:
            ax.axhline(0, color=MUTED, lw=0.8)
    axes[0].legend(loc="upper left")
    fig.text(0.01, -0.04, "Error bars: SD over 3 seeds of the 10-fold mean (fold-to-fold SD is about 0.1 AUC; see results.md).",
             fontsize=7, color=MUTED)
    fig.savefig(FIG / "fig4_real.png")
    plt.close(fig)
    md.extend(["## 4. Real autism labels (no planting; real hospitals as sites)", "",
               "| Model | Method | Test accuracy | Test AUC | Explanation-site Spearman | Top-45 overlap with site edges (chance 0.007) |",
               "|---|---|---|---|---|---|"])
    for (model, m), r in s.iterrows():
        md.append(f"| {model.upper()} | {METH[m].replace(chr(10), ' ')} | {fmt(*r['test_acc'])} | {fmt(*r['test_auc'])} | "
                  f"{fmt(*r['site_spearman'])} | {fmt(*r['site_top_share'])} |")
    md.append("")


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    for fn in (fig_recovery, fig_drift, fig_methods, fig_real):
        try:
            fn()
            print(f"{fn.__name__}: ok")
        except Exception as e:  # keep going; report
            print(f"{fn.__name__}: FAILED ({e!r})")
    (ROOT / "docs" / "results.md").write_text("\n".join(md) + "\n", encoding="utf8")
    print("wrote docs/results.md")


if __name__ == "__main__":
    main()
